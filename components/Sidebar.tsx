export function Sidebar() {
  const pathname = usePathname();

  return (
    <aside className="hidden md:flex md:w-64 shrink-0 flex-col border-r border-outline-variant/40 bg-surface px-4 py-6">
      <div className="flex items-center gap-2 px-2 mb-8">
        <Mascot size={32} expression="neutral" />
        <div>
          <p className="font-extrabold text-lg leading-none text-on-surface">MoodMate</p>
          <p className="text-xs text-on-surface-variant">Your wellness companion</p>
        </div>
      </div>

      <nav className="flex flex-col gap-1">
        {NAV.map((item) => {
          const active = pathname === item.href;
          const Icon = item.icon;
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-4 py-2.5 rounded-2xl text-sm font-semibold transition-transform hover:scale-[1.02] ${
                active
                  ? "bg-primary-container text-on-primary-container"
                  : "text-on-surface-variant hover:bg-surface-container"
              }`}
            >
              <Icon className="w-5 h-5 shrink-0" />
              {item.label}
            </Link>
          );
        })}
      </nav>

      <div className="mt-auto pt-6 flex items-center gap-2 px-2 text-xs text-on-surface-variant">
        <LockIcon className="w-3.5 h-3.5" />
        Your data stays on this device
      </div>
    </aside>
  );
}

